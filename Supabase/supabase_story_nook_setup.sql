create or replace function public.protect_profile_engagement_fields()
returns trigger language plpgsql security definer set search_path = public as $$
begin
    if current_setting('story_nook.allow_points_update', true) = 'on' then
        return new;
    end if;

    if auth.uid() = old.id and not story_nook_private.is_nook_admin() then
        new.points_total = old.points_total;
        new.level = old.level;

        if new.selected_flair_id is not null
           and new.selected_flair_id is distinct from old.selected_flair_id
           and not exists (
               select 1
               from public.user_flairs uf
               where uf.user_id = old.id
                 and uf.flair_id = new.selected_flair_id
           ) then
            raise exception 'That flair has not been unlocked yet.';
        end if;
    end if;

    return new;
end;
$$;
revoke execute on function public.protect_profile_engagement_fields() from public, anon, authenticated;


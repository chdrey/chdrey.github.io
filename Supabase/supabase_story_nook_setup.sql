create or replace function public.record_point_event(
    p_user_id uuid,
    p_event_type text,
    p_points integer,
    p_story_id bigint default null,
    p_comment_id bigint default null,
    p_prompt_id bigint default null,
    p_source_user_id uuid default null,
    p_note text default null
)
returns void language plpgsql security definer set search_path = public as $$
declare
    v_points integer;
    v_new_total integer;
begin
    if p_user_id is null or p_points = 0 then
        return;
    end if;

    insert into public.point_events (
        user_id,
        event_type,
        points,
        story_id,
        comment_id,
        prompt_id,
        source_user_id,
        note
    )
    values (
        p_user_id,
        p_event_type,
        p_points,
        p_story_id,
        p_comment_id,
        p_prompt_id,
        p_source_user_id,
        p_note
    )
    on conflict do nothing
    returning points into v_points;

    if v_points is null then
        return;
    end if;

    perform set_config('story_nook.allow_points_update', 'on', true);

    update public.profiles
       set points_total = greatest(0, points_total + v_points)
     where id = p_user_id
     returning points_total into v_new_total;

    update public.profiles
       set level = greatest(1, floor(sqrt(v_new_total::numeric / 50))::integer + 1)
     where id = p_user_id;

    perform set_config('story_nook.allow_points_update', 'off', true);
end;
$$;
revoke execute on function public.record_point_event(uuid, text, integer, bigint, bigint, bigint, uuid, text) from public, anon, authenticated;

create or replace function public.award_story_post_points()
returns trigger language plpgsql security definer set search_path = public as $$
begin
    if new.user_id is not null then
        perform public.record_point_event(new.user_id, 'posted_story', 10, new.id, null, new.prompt_id, null, null);
    end if;
    return new;
end;
$$;
revoke execute on function public.award_story_post_points() from public, anon, authenticated;

create or replace function public.award_story_like_points()
returns trigger language plpgsql security definer set search_path = public as $$
declare
    v_story_owner uuid;
    v_prompt_id bigint;
begin
    select s.user_id, s.prompt_id
      into v_story_owner, v_prompt_id
      from public.stories s
     where s.id = new.story_id
       and s.deleted_at is null;

    if v_story_owner is not null and v_story_owner <> new.user_id then
        perform public.record_point_event(v_story_owner, 'received_like', 1, new.story_id, null, v_prompt_id, new.user_id, null);
    end if;

    return new;
end;
$$;
revoke execute on function public.award_story_like_points() from public, anon, authenticated;

create or replace function public.award_story_comment_points()
returns trigger language plpgsql security definer set search_path = public as $$
declare
    v_story_owner uuid;
    v_prompt_id bigint;
begin
    select s.user_id, s.prompt_id
      into v_story_owner, v_prompt_id
      from public.stories s
     where s.id = new.story_id
       and s.deleted_at is null;

    if v_story_owner is not null and (new.user_id is null or v_story_owner <> new.user_id) then
        perform public.record_point_event(v_story_owner, 'received_comment', 2, new.story_id, new.id, v_prompt_id, new.user_id, null);
    end if;

    return new;
end;
$$;
revoke execute on function public.award_story_comment_points() from public, anon, authenticated;

